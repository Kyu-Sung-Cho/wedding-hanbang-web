/**
 * 강압적 통제 신호 — 중재 요청에만 쓰는 낮은 문턱.
 *
 * ## ⚠ 먼저 읽을 것: 이것은 안전 경계가 아니다 (2026-08-06 측정)
 *
 * 이 파일을 만든 사람이 "이걸로 막았다"고 믿었다. 측정해 보니 아니었다.
 *
 * 실제 사람이 쓸 법한 강압적 통제 서술 45개를 이 저장소 바깥에서 따로 만들어
 * 넣었더니 **45개 중 0개**가 걸렸다. 걸린 것은 이 파일을 만들 때 함께 상상해서
 * 쓴 예시 문장들뿐이었다. 탐지기와 그 테스트를 같은 머릿속에서 만들면, 테스트는
 * "코드가 만든 사람의 상상과 일치한다"만 증명한다.
 *
 * 낱말을 넓혀서 고쳐지지 않는다. 실제로 넓혀 봤고, 탐지는 45개 중 1개로만
 * 올라간 반면 평범한 결혼 대화 30개 중 15개를 잘못 걸었다("예식장 계약금 카드로
 * 긁으면 무이자 할부 승인 되는지", "친구들 만나기로 한 약속을 자꾸 못 지켜서").
 * 그 판은 되돌렸다. 사람은 자기 상황을 낱말로 신고하지 않고 상황으로 이야기한다 —
 * "월급날만 되면 걔가 알아서 싹 옮겨놔요", "동창들 모임 얘기만 나와도 며칠을 입을
 * 닫아버려서 이제 그냥 안 나간다고 해요". 정규식이 닿는 표면이 아니다.
 *
 * 그래서 이 함수는 **보조 신호**다. 여기 걸리면 확실히 중재를 멈춰야 하지만,
 * 여기 안 걸린다고 안전한 것이 아니다. 안전은 탐지에 의존하지 않는 곳에서 와야
 * 한다. 측정 근거는 `coerciveControlRecall.test.ts`에 있고, 그 파일의 문장들은
 * 이 파일을 고치는 사람이 쓰지 않는다.
 *
 * ## 왜 따로 두는가
 *
 * 일반 위험 분류기는 폭력을 가리키는 낱말(때리다, 협박, 감금…)을 본다. 그런데 사람이
 * 실제로 쓰는 말은 그렇지 않다. "강압적 통제를 당하고 있어요"라고 말하는 사람은 거의
 * 없고, "통장을 다 가져갔어요", "친구를 못 만나게 해요", "제 폰을 매일 확인해요"라고
 * 말한다. 이 문장들은 기존 낱말 목록에 걸리지 않는다.
 *
 * 그렇다고 일반 분류기의 어휘를 넓히면 평범한 결혼 대화가 고위험으로 떨어진다.
 * "예산은 신랑이 관리해요"에 도구가 전부 차단되면 그 자체가 제품 실패다.
 *
 * ## 그래서 중재에서만 문턱을 낮춘다
 *
 * 두 실패의 무게가 다르기 때문이다.
 *
 *   놓쳤을 때 — 강압을 겪는 사람이 "두 분이 조금씩 양보하세요" 카드를 받는다.
 *               그 카드는 상대와 공유될 수 있다.
 *   과했을 때 — 합의안 초안 대신 "확인된 사실을 정리하고 공식 기관에 물어볼 질문을
 *               준비하자"는 답을 받는다.
 *
 * 뒤쪽은 안전한 실패다. 그래서 여기서는 의심만으로 멈춘다 — 문서 §9의 "의심되면"이
 * 그 뜻이다.
 *
 * ## 판정하지 않는다
 *
 * 이 함수는 "이 관계는 학대다"를 말하지 않는다. 지금 이 대화를 합의안으로 끌고 가면
 * 안 된다는 것만 말한다. 관계에 대한 판단, 상대에 대한 규정, 신고 권유는 하지 않는다.
 */

/** 경제적 통제 — 돈을 쥐어 상대를 묶는 형태. 단순한 재정 분담과 구분해야 한다. */
const ECONOMIC_CONTROL_RE =
  /(?:통장|카드|월급|생활비|돈|계좌|수입)(?:을|를|은|는|도)?[^.!?\n]{0,20}(?:못\s*쓰게|못쓰게|안\s*줘|안줘|주지\s*않|빼앗|뺏|가져가|가져갔|맡기라|허락\s*(?:을\s*)?받|허락받)/u;

/** 감시·추적 — 한 번 확인이 아니라 반복·전면 확인이어야 한다. */
const SURVEILLANCE_RE =
  /(?:위치|어디\s*(?:에\s*)?있는지|폰|휴대폰|핸드폰|카톡|메시지|문자|통화\s*(?:목록|내역))(?:을|를|은|는|도)?[^.!?\n]{0,24}(?:다\s*확인|계속\s*확인|매일\s*확인|늘\s*확인|검사|뒤져|추적|감시|보여\s*줘야|보여줘야|공유\s*해야|공유해야)/u;

/** 고립 — 사람을 끊게 만드는 형태. */
const ISOLATION_RE =
  /(?:친구|가족|부모님|엄마|아빠|동료)(?:들)?(?:을|를|은|는|도|하고|랑|와|과)?[^.!?\n]{0,20}(?:못\s*만나게|만나지\s*말|연락하지\s*말|연락\s*끊|끊으라|끊으래)/u;

/** 강압 — 허락을 받아야 하는 구조. */
const COERCION_RE =
  /(?:시키는\s*대로|말\s*안\s*들으면|말을\s*안\s*들으면|허락\s*없이(?:는)?\s*(?:못|안)|마음대로\s*(?:못|안)|내\s*허락)/u;

/** 보복 위협 — 떠나거나 말하면 무슨 일이 생긴다는 형태. */
const RETALIATION_RE =
  /(?:헤어지자고?\s*하면|헤어지면|말하면|얘기하면|신고하면|알리면)[^.!?\n]{0,24}(?:가만\s*(?:안|두지)|죽|해코지|망하게|망칠|알리겠|퍼뜨리|폭로)/u;

const SIGNALS = [
  ["economic_control", ECONOMIC_CONTROL_RE],
  ["surveillance", SURVEILLANCE_RE],
  ["isolation", ISOLATION_RE],
  ["coercion", COERCION_RE],
  ["retaliation_threat", RETALIATION_RE],
] as const;

export type CoerciveControlSignal = (typeof SIGNALS)[number][0];

/**
 * 이 문장을 합의안으로 끌고 가면 안 되는가.
 *
 * 중재 요청에만 쓴다. 일반 대화에 쓰면 평범한 재정·일정 이야기가 고위험으로 떨어진다.
 */
export function findCoerciveControlSignals(text: unknown): CoerciveControlSignal[] {
  if (typeof text !== "string" || text.length === 0) return [];
  return SIGNALS
    .filter(([, pattern]) => pattern.test(text))
    .map(([name]) => name);
}

export function hasCoerciveControlSignal(text: unknown): boolean {
  return findCoerciveControlSignals(text).length > 0;
}
