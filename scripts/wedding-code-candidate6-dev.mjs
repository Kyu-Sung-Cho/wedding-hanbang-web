import { spawn } from "node:child_process";
import { randomUUID } from "node:crypto";
import { mkdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { acquireWeddingCodeResearchLock } from "./wedding-code-research-lock.mjs";
import { removeOwnedWeddingCodeResearchRoute } from "./wedding-code-research-route-artifact.mjs";
import { buildWeddingCodeResearchEnvironment } from "./wedding-code-research-env.mjs";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(scriptDirectory, "../apps/web");
const nextCli = path.join(appRoot, "node_modules/next/dist/bin/next");
const port = process.env.PORT ?? "3106";
const routeDirectory = path.join(
  appRoot,
  "src/app/internal/wedding-code-research"
);
const generatedRoute = path.join(routeDirectory, "page.tsx");
const developmentArtifacts = path.resolve(appRoot, ".next/dev");
const generatedRouteNonce = randomUUID();
const generatedRouteSource = [
  "// Generated by scripts/wedding-code-candidate6-dev.mjs.",
  `// Artifact nonce: ${generatedRouteNonce}`,
  "// Never commit this local-only route.",
  'import LocalPreviewPage, { metadata as localMetadata } from "@/lib/weddingCode/research/localPreviewPage";',
  "export const dynamic = \"force-dynamic\";",
  "export const revalidate = 0;",
  "export const metadata = localMetadata;",
  "export default LocalPreviewPage;",
  "",
].join("\n");

const releaseLock = await acquireWeddingCodeResearchLock("local-research-preview");

try {
  await mkdir(routeDirectory, { recursive: true });
  await writeFile(generatedRoute, generatedRouteSource, { encoding: "utf8", flag: "wx" });
} catch (error) {
  await releaseLock();
  throw error;
}

const child = spawn(
  process.execPath,
  [nextCli, "dev", "--hostname", "127.0.0.1", "--port", port],
  {
    cwd: appRoot,
    env: buildWeddingCodeResearchEnvironment(),
    stdio: "inherit",
  }
);

let cleanupPromise;

function cleanup() {
  cleanupPromise ??= (async () => {
    try {
      if (!developmentArtifacts.startsWith(`${appRoot}${path.sep}`)) {
        throw new Error("Refusing to remove development artifacts outside apps/web");
      }
      await removeOwnedWeddingCodeResearchRoute({
        expectedSource: generatedRouteSource,
        generatedRoute,
        routeDirectory,
      });
      await rm(developmentArtifacts, { recursive: true, force: true });
    } finally {
      await releaseLock();
    }
  })();
  return cleanupPromise;
}

let finishPromise;
function finish(code, error) {
  finishPromise ??= (async () => {
    if (error) console.error(error);
    await cleanup();
    process.exit(code);
  })();
  return finishPromise;
}

for (const signal of ["SIGINT", "SIGTERM"]) {
  process.on(signal, () => child.kill(signal));
}

process.on("message", (message) => {
  if (message === "shutdown") child.kill("SIGTERM");
});

child.on("error", async (error) => {
  await finish(1, error);
});

child.on("exit", async (code) => {
  await finish(code ?? 1);
});
