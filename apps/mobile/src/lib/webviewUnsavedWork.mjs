/* global URL */
/**
 * 웹뷰가 연 화면이 **저장되지 않은 작업**을 들고 있는가.
 *
 * 웨딩코드는 고른 답을 문서의 화면 상태로만 들고 있다. 주소에 실리는 것은 비교
 * 링크를 만든 뒤뿐이다. 그래서 문서를 다시 읽으면 답한 것이 통째로 사라진다 —
 * 그것도 아무 말 없이, 처음 화면으로. 당겨서 새로고침은 그 일을 손가락 하나로
 * 일으킨다.
 *
 * **왜 화면 파일이 아니라 여기 있나.** `webview.tsx` 안의 함수였을 때는 검사가
 * "그런 함수가 있나" 만 물을 수 있었다. 실제로 `/wedding-code` 를 `/wedding-codes`
 * 로 한 글자 바꿔 심었더니 이 판정이 늘 false 가 되는데도 테스트 10개가 전부
 * 초록불이었다(2026-09-16). 답을 아는 함수는 답을 물어볼 수 있는 곳에 둔다.
 *
 * @param {string} url 웹뷰가 지금 보고 있는 주소
 * @returns {boolean}
 */
export function holdsUnsavedWork(url) {
  try {
    return /^\/wedding-code(\/|$)/.test(new URL(url).pathname);
  } catch {
    // 주소를 못 읽으면 새로고침을 막지 않는다. 막아서 얻는 것보다, 멀쩡한 화면에서
    // 새로고침이 사라져 빠져나갈 길이 없어지는 쪽이 더 나쁘다.
    return false;
  }
}
