import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";
import { fileURLToPath, URL } from "node:url";

const onboardingPath = fileURLToPath(
  new URL("../../app/onboarding/index.tsx", import.meta.url),
);
const generatorMigrationPath = fileURLToPath(
  new URL(
    "../../../../supabase/migrations/20260714160000_harden_amora_privacy_boundaries.sql",
    import.meta.url,
  ),
);

const onboardingSource = readFileSync(onboardingPath, "utf8");
const generatorMigrationSource = readFileSync(generatorMigrationPath, "utf8");

// Regression: the database issues `WH-` plus 12 characters, but mobile used to
// truncate partner codes at 10 characters and made every new join impossible.
test("mobile onboarding accepts the full invite code generated by the database", () => {
  assert.match(
    generatorMigrationSource,
    /v_code\s*:=\s*'WH-'[\s\S]*?\),\s*1,\s*12\)\);/,
  );
  assert.match(
    onboardingSource,
    /placeholder="초대코드 입력 \(예: WH-ABC123DEF456\)"[\s\S]*?maxLength=\{15\}/,
  );
});
