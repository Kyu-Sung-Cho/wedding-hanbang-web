export function buildPlanChangeRpcDiagnostic(error: unknown): Error {
  const code = isRecord(error) ? error.code : undefined;
  const sqlstate = typeof code === "string"
    && code.length === 5 && /^[0-9A-Z]{5}$/.test(code)
    ? code
    : "unknown";
  const message = isRecord(error) ? error.message : undefined;
  const reason = typeof message === "string" && SAFE_REASONS.has(message)
    ? message
    : "unknown";

  // 운영 log.error는 plain object를 버린다. 검증된 표식만 담은 새 Error로
  // 바꾸며 원래 message/details/hint/stack/cause/식별자는 전달하지 않는다.
  return new Error(`Journey plan-change RPC failed [sqlstate=${sqlstate}; reason=${reason}]`);
}
