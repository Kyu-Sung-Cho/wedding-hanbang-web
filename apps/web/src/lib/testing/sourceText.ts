// 테스트 전용 헬퍼.
//
// 소스를 문자열로 읽어 계약을 검사하는 테스트는 흔히 "사용자/모델이 실제로 받는
// 문구"만 봐야 한다. 주석에는 "예전에는 여기 X가 있었다"는 설명을 남길 수 있어야
// 하는데, 주석까지 훑으면 그 설명 자체가 위반으로 잡힌다.

/** `//` 줄 주석과 `/* *\/` 블록 주석을 지운다. `https://`는 보존한다. */
export function stripComments(source: string): string {
  return source
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/(^|[^:])\/\/.*$/gm, "$1");
}
