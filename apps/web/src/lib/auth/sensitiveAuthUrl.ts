const AUTH_PARAMETER_NAMES = [
  "access_token",
  "refresh_token",
  "id_token",
  "provider_token",
  "provider_refresh_token",
  "token",
  "token_hash",
  "recovery_token",
  "confirmation_token",
  "email_change_token_current",
  "email_change_token_new",
  "code",
  "auth_code",
  "authorization_code",
  "code_verifier",
  "client_secret",
  "otp",
  "state",
] as const;

const AUTH_ERROR_PARAMETER_NAMES = [
  "error",
  "error_code",
  "error_description",
  "error_message",
  "error_reason",
  "error_uri",
] as const;

export type PendingPasswordRecovery = {
  kind: "token_hash";
  tokenHash: string;
};

interface AuthCallbackVault {
  loginError: boolean;
  mobileOAuthCode: string | null;
  passwordRecovery: PendingPasswordRecovery | null;
}

const AUTH_CALLBACK_VAULT_PROPERTY = "__HANBANG_AUTH_CALLBACK_VAULT__";

function isAuthCallbackVault(value: unknown): value is AuthCallbackVault {
  return typeof value === "object"
    && value !== null
    && Reflect.has(value, "loginError")
    && Reflect.has(value, "mobileOAuthCode")
    && Reflect.has(value, "passwordRecovery");
}

function getAuthCallbackVault(): AuthCallbackVault | null {
  if (typeof window === "undefined") return null;

  const existing = Reflect.get(window, AUTH_CALLBACK_VAULT_PROPERTY);
  if (isAuthCallbackVault(existing)) return existing;

  const vault: AuthCallbackVault = {
    loginError: false,
    mobileOAuthCode: null,
    passwordRecovery: null,
  };
  Object.defineProperty(window, AUTH_CALLBACK_VAULT_PROPERTY, {
    configurable: true,
    enumerable: false,
    value: vault,
    writable: false,
  });
  return vault;
}

function discardEmptyVault(vault: AuthCallbackVault): void {
  if (
    !vault.loginError
    && !vault.mobileOAuthCode
    && !vault.passwordRecovery
    && typeof window !== "undefined"
  ) {
    Reflect.deleteProperty(window, AUTH_CALLBACK_VAULT_PROPERTY);
  }
}

function nonEmpty(value: string | null): string | null {
  const trimmed = value?.trim();
  return trimmed ? trimmed : null;
}

function hasSensitiveParameter(parameters: URLSearchParams): boolean {
  return AUTH_PARAMETER_NAMES.some((name) => parameters.has(name));
}

function clearSensitiveSearchParameters(parameters: URLSearchParams): void {
  AUTH_PARAMETER_NAMES.forEach((name) => parameters.delete(name));
}

function hasAuthErrorParameter(parameters: URLSearchParams): boolean {
  return AUTH_ERROR_PARAMETER_NAMES.some((name) => parameters.has(name));
}

function clearAuthErrorParameters(parameters: URLSearchParams): void {
  AUTH_ERROR_PARAMETER_NAMES.forEach((name) => parameters.delete(name));
}

function replaceCurrentUrl(url: URL): void {
  const destination = `${url.pathname}${url.search}${url.hash}`;
  window.history.replaceState(window.history.state, "", destination || "/");
}

/**
 * Captures callback material in module memory, then removes it synchronously
 * from browser history before observability SDKs or React effects can read it.
 */
export function captureAndClearSensitiveAuthUrl(): void {
  if (typeof window === "undefined") return;

  const url = new URL(window.location.href);
  const isPasswordRecovery = url.pathname === "/reset-password";
  const isMobileCallback = url.pathname === "/auth/mobile-callback";
  const isLogin = url.pathname === "/login" || url.pathname === "/demo/login";
  if (!isPasswordRecovery && !isMobileCallback && !isLogin) return;

  const fragment = new URLSearchParams(url.hash.replace(/^#/, ""));
  const searchHasSecrets = hasSensitiveParameter(url.searchParams);
  const fragmentHasSecrets = hasSensitiveParameter(fragment);
  const searchHasAuthError = hasAuthErrorParameter(url.searchParams);
  const fragmentHasAuthError = hasAuthErrorParameter(fragment);

  if (
    !searchHasSecrets
    && !fragmentHasSecrets
    && !searchHasAuthError
    && !fragmentHasAuthError
  ) return;
  const vault = getAuthCallbackVault();
  if (!vault) return;

  if (isLogin) {
    // Provider descriptions can contain email addresses or internal details.
    // Retain only the fact that callback material was present so the UI can
    // show fixed copy without leaving raw provider data in history/telemetry.
    vault.loginError = true;
  } else if (isPasswordRecovery) {
    const tokenHash = nonEmpty(
      url.searchParams.get("token_hash") ?? fragment.get("token_hash"),
    );

    // Password changes accept only a one-time recovery token generated by our
    // server. An ordinary session or OAuth/PKCE code must never be promoted to
    // password-recovery authority merely because it appeared on this route.
    if (tokenHash) {
      vault.passwordRecovery = { kind: "token_hash", tokenHash };
    }
  } else if (isMobileCallback) {
    vault.mobileOAuthCode = nonEmpty(
      url.searchParams.get("code")
      ?? url.searchParams.get("auth_code")
      ?? url.searchParams.get("authorization_code"),
    );
  }

  clearSensitiveSearchParameters(url.searchParams);
  clearAuthErrorParameters(url.searchParams);
  // Supabase implicit-flow fragments are entirely callback metadata. Clearing
  // the whole fragment avoids retaining token lifetime and recovery markers.
  if (fragmentHasSecrets || fragmentHasAuthError) url.hash = "";
  replaceCurrentUrl(url);
  discardEmptyVault(vault);
}

export function consumePendingLoginError(): boolean {
  const vault = getAuthCallbackVault();
  if (!vault) return false;
  const pending = vault.loginError;
  vault.loginError = false;
  discardEmptyVault(vault);
  return pending;
}

export function consumePendingPasswordRecovery(): PendingPasswordRecovery | null {
  const vault = getAuthCallbackVault();
  if (!vault) return null;
  const pending = vault.passwordRecovery;
  vault.passwordRecovery = null;
  discardEmptyVault(vault);
  return pending;
}

export function consumePendingMobileOAuthCode(): string | null {
  const vault = getAuthCallbackVault();
  if (!vault) return null;
  const code = vault.mobileOAuthCode;
  vault.mobileOAuthCode = null;
  discardEmptyVault(vault);
  return code;
}
