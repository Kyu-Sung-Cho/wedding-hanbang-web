/** 새 변경을 부탁한 턴에는 이전 확인 카드와 대기열을 현재 요청의 맥락으로 넘기지 않는다. */
export function hasNewAmoraChangeIntent(userText: string): boolean {
  const text = userText.normalize("NFKC").trim();
  // 말로 동의해도 실행 권한은 생기지 않는다. 기존 카드를 다시 보여주는 흐름만 유지한다.
  if (/^(?:(?:네|예|응|좋아(?:요)?|그래(?:요)?|알겠(?:어|어요))\s*[,!.]?\s*)?(?:(?:이대로|그대로|그렇게|(?:방금|기존|위)\s*(?:제안|내용)(?:대로)?)\s*)?(?:(?:적용|반영|저장)\s*)?(?:해\s*(?:줘|주세요)|하자|해|할게(?:요)?)[.!?]*$/u.test(text)) return false;
  return /(?:추가|등록|저장|반영|변경|수정|삭제|취소|적용|설정|기록|배분|배정|분배|체크)\s*(?:해\s*(?:줘|주세요|주실|줄)|하고\s*싶어|하자|해라)|(?:바꿔|고쳐|지워|옮겨|넣어|잡아|미뤄|당겨|올려|내려|줄여|늘려|나눠|맞춰|정해)\s*(?:줘|주세요|주실|줄)|완료\s*(?:처리\s*)?해\s*(?:줘|주세요)/u.test(text);
}
