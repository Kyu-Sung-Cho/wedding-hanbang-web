/**
 * 모델이 답변 끝에 한국어 웹 스팸을 붙여 내보내는 것을 막는다.
 *
 * 2026-08-25 운영에서 실제로 나갔다. 예산 요약 답변의 마지막 줄이 이랬다:
 *
 *   - 기록된 지출: **0원**출장안마
 *
 * 도구 결과에는 그 말이 없었고(`get_budget_summary` 출력 확인), 커플의 저장
 * 데이터에도 없었다. 모델이 만들어냈다 — 한국어 웹 문서 끝에 SEO 스팸이
 * 달려 있는 형태가 학습 데이터에 흔해서 나오는 꼬리 아티팩트다.
 *
 * 운영 아모라 답변 625건을 훑어 1건(0.16%)이었다. 낮아 보이지만 결혼을
 * 준비하는 사람에게 성인업소 문구가 한 번 보이는 것으로 충분히 나쁘다.
 *
 * ## 어휘로 자른다. 구조로 자르려다 정상 문장을 부술 뻔했다.
 *
 * 처음엔 "마크다운 굵게 닫힘 뒤에 공백 없이 붙은 한글 조각" 이라는 구조
 * 규칙을 썼다. 운영 코퍼스 625건에서 오탐이 0건이라 통과시킬 뻔했는데,
 * 아모라가 실제로 쓰는 문장 끝을 대보니 7개 중 7개를 잘랐다:
 *
 *   "현재 저장된 총예산은 **6,200만 원**이에요"  → "이에요" 를 삭제
 *   "계약서에 항목이 적혀 있는지 **꼭 확인**하세요" → "하세요" 를 삭제
 *
 * 코퍼스에 그 형태가 1건뿐이라 0오탐이 나온 것이었다. 코퍼스를 통과했다는
 * 사실만으로는 아무것도 증명되지 않는다.
 *
 * ## 한계 — 알고 남겨둔다
 *
 * 꼬리만 자른다. 문장 한가운데에 같은 말이 섞여 나오면 잘라내지 않는다.
 * 그 자리를 지우면 문장이 깨지고, 깨진 문장을 사용자에게 보이는 것이 더
 * 나은지 확신할 근거가 없다. 관측된 형태는 전부 꼬리였다(1/1).
 */

/**
 * 결혼 준비 대화에서 정당한 쓰임이 없는 말만 넣는다.
 *
 * `카지노`(신혼여행지), `마사지`(스파), `유흥비`(예산 항목) 처럼 실제로
 * 쓰일 수 있는 말은 일부러 넣지 않았다. 여기 있는 것들은 붙여 쓴 형태
 * 자체가 업소 광고 문구다.
 */
const SPAM_TAIL_TERMS = [
  "출장\\s?안마",
  "출장\\s?마사지",
  "안마방",
  "립카페",
  "풀싸롱",
  "룸싸롱",
  "룸살롱",
  "성인용품",
  "성인화상",
  "비아그라",
  "시알리스",
  "토토사이트",
  "먹튀검증",
  "바카라사이트",
  "밤알바",
  "조건만남",
];

/**
 * 스팸 어휘가 나타나는 자리.
 *
 * 앞에 한글이 붙어 있으면 다른 낱말의 일부다 — `드립카페` 의 `립카페` 를
 * 잘라 `드` 한 글자만 남기던 결함이 실제로 있었다.
 *
 * `건마` 는 아예 뺐다. 앞 글자가 숫자면 경계 검사를 통과하는데
 * (`5건마다`·`3건마`) 그건 평범한 한국어다. 두 글자짜리는 그만큼 위험하다.
 */
const SPAM_TERM_SOURCE = `(?<![가-힣])(?:${SPAM_TAIL_TERMS.join("|")})`;

/**
 * 스팸 어휘 뒤에 얼마나 더 붙어 있어도 꼬리로 볼 것인가.
 *
 * 처음엔 `[\s\p{P}]*$` 로 문장 끝만 봤다. 그래서 전화번호나 주소가 붙은
 * 형태 — **실제로 클릭을 유도하는 쪽** — 이 통째로 살아남았다. 어휘만 덩그러니
 * 있는 무해한 형태는 잘리고 유해한 형태는 나가는 역전이었다.
 */
const MAX_SPAM_TAIL_CHARS = 80;

export function stripAmoraSpamTail(text: string): string {
  if (typeof text !== "string" || text.length === 0) return text;
  // 정규식을 매번 새로 만든다. 전역 플래그의 `lastIndex` 를 모듈 수준에서
  // 공유하면 호출 순서에 따라 결과가 달라진다.
  for (const match of text.matchAll(new RegExp(SPAM_TERM_SOURCE, "gu"))) {
    if (match.index === undefined) continue;
    // 본문 한가운데는 자르지 않는다. 자르면 문장이 깨지고, 깨진 문장을
    // 보이는 것이 나은지 확신할 근거가 없다.
    if (text.length - match.index > MAX_SPAM_TAIL_CHARS) continue;
    // **첫 번째** 자리에서 끝까지 자른다. 모델이 꼬리를 두 번 붙이면
    // 마지막 것만 자르는 규칙은 하나를 남긴다.
    const kept = text.slice(0, match.index).trimEnd();
    // 답변이 통째로 스팸이면 자를 것이 아니라 다른 문제다. 빈 답을 만들지 않는다.
    return kept.length === 0 ? text : kept;
  }
  return text;
}
