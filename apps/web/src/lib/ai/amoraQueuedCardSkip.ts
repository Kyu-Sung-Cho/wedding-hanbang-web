/**
 * 여러 변경을 한 번에 부탁한 대기열에서 **지금 카드만 건너뛰는** 턴을 알아본다 (2026-09-18).
 *
 * 고치기 전(2026-09-17 재검사, 모델 답을 고정한 경로 테스트로 매번 재현):
 *
 *   사용자: "예산에 드레스 350만원, 헤어메이크업 70만원, 결혼식장 1600만원 넣어줘"
 *   아모라: (결혼식장 카드) "나머지 2건은 이 확인이 끝나면 이어서 제안할게요."
 *   사용자: (적용) → "3건 중 1건 반영했어요. 다음 항목을 확인해 주세요." (드레스 카드)
 *   사용자: (드레스 카드에서 "지금은 적용하지 않기")
 *
 * "지금은 적용하지 않기" 는 화면에서만 치우는 버튼이라 서버에 아무것도 보내지 않는다. 대기열은
 * 적용해야만 앞으로 가므로, 헤어메이크업은 드레스 카드 뒤에서 기다리다가 이월 상한(2턴)이나 새
 * 변경 요청에서 **아무 말 없이** 사라졌다. 드레스만 빼고 싶은 사람에게 남은 길은 드레스를
 * 적용하거나 요청을 처음부터 다시 쓰는 것뿐이었다.
 *
 * 그래서 대기열 카드에 "이 항목 건너뛰기" 버튼을 따로 두고, 버튼은 아래 **고정 문장**을 보낸다.
 * 라우트는 이 문장일 때만 지금 카드를 반영하지 않은 채 다음 항목을 **새 확인 카드**로 낸다.
 *
 * 판정은 고정 문장 완전일치 하나다. "스튜디오 예산은 안 할래" 같은 자연어 거절은 받지 않는다 —
 * 무엇을 빼라는지 문장만으로는 틀릴 수 있고, 틀리면 사용자가 원한 항목을 건너뛴다. 그런 말은
 * 지금까지의 경로(범위 판정·모델 답변)를 그대로 탄다.
 *
 * 이 함수는 **실행 권한을 만들지 않는다.** 참이어도 라우트는 어떤 도구도 실행하지 않고,
 * 건너뛴 카드의 action_id 를 다시 발급하지도 않는다. 다음 항목도 사용자가 그 카드의 버튼을
 * 눌러야 반영된다.
 *
 * 이 문장은 범위 판정에서 W4(범위 밖, 장기 기억 꺼짐)로 떨어진다. 라우트는 이 판정을 바꾸지
 * 않는다 — "적용하지 않기" 턴이 기억 저장 대상이 되면 안 된다.
 *
 * 모바일도 같은 문장을 보낸다(`apps/mobile/src/lib/pendingAmoraAction.ts`). 두 값이 같은지
 * 검사가 따로 있다.
 */
export const AMORA_QUEUED_CARD_SKIP_TEXT = "이 항목은 적용하지 않고 다음 항목으로 넘어갈게요.";

export function isAmoraQueuedCardSkip(text: unknown): boolean {
  return typeof text === "string"
    && text.normalize("NFC").trim() === AMORA_QUEUED_CARD_SKIP_TEXT;
}
