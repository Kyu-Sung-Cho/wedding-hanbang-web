const REVIEW3_BASES: readonly string[] = ["내일 죽을 예정이야", "오늘 죽으려고", "죽기로 했어"];
/** 검토자와 같은 세 자리: 끝(띄어서)·끝(붙여서)·앞. */
const atThreePlaces = (mark: string) =>
  REVIEW3_BASES.flatMap((base) => [`${base} ${mark}`, `${base}${mark}`, `${mark} ${base}`]);
/** 구분자만으로 된 얼굴. 우는 얼굴 `;-;` 만 빼고 어휘 밖 토큰이다. */
const SEPARATOR_FACES: readonly string[] = ["-.-", "-,-", ".-.", ":-:", "\u{B7}-\u{B7}"];
const SEPARATOR_FACE_ROWS: readonly string[] = SEPARATOR_FACES.flatMap(atThreePlaces);
/** 얼굴이 아니어서 원래 서지 않던 대조(`_`·자모·물결 U+301C·빼기 U+2212 는 구분자가 아니다). */
const NON_SEPARATOR_FACE_ROWS: readonly string[] = [
  "-_-", "\u{3160}_\u{3160}", "T_T", "\u{301C}", "\u{2212}",
].flatMap(atThreePlaces);
/**
 * 정규화가 구분자로 접는 표시. 그리스 물음표 U+037E 는 NFC 에서 이미 `;` 로 바뀌고(정준 분해),
 * 겹느낌표 U+203C 는 NFKC 에서 `!!` 가 된다. `classifyAmoraCrisis` 와 범위 분류는 정규화한
 * 글을 판정기에 넘기므로 규칙은 이 두 글자를 **볼 수 없다.** 원문 쪽에서만 막으면 두 입구가
 * 갈리고(원문은 안 서고 정규화본은 선다), 고정 안내는 정규화본 쪽이 정한다 — 그래서 원문 쪽
 * 검사는 넣지 않았다. 이 행들은 `;`·`!!` 를 쓴 같은 문장과 똑같이 판정된다.
 */
const NORMALISER_FOLDED_ROWS: readonly string[] = [
  ...atThreePlaces("\u{203C}\u{FE0F}"),
  ...atThreePlaces("\u{37E}"),
];

describe("(vii) 세 번째 검토 — 얼굴·임박상·애교 어미·맨 전에·두 입구", () => {
  it("구분자만으로 된 얼굴 45행(얼굴 5 × 문장 3 × 자리 3) — 하나도 서지 않는다", () => {
    expect(SEPARATOR_FACE_ROWS).toHaveLength(45);
    const fired = SEPARATOR_FACE_ROWS.filter((text) => !sameAsBase(text));
    expect(fired).toEqual([]);
    // 같은 문장이 얼굴 없이는 선다 — 막은 것은 얼굴이다.
    for (const base of REVIEW3_BASES) expect(assess(base), base).toEqual(PLANNED_STATEMENT_VERDICT);
  });

  it("전각으로 쓴 얼굴도 정규화한 뒤 얼굴이다", () => {
    for (const text of atThreePlaces("\u{FF0D}\u{FF0E}\u{FF0D}")) {
      expect(assess(text), text).toEqual(assessBase(text));
    }
  });

  it("우는 얼굴 `;-;` 은 우는 자모처럼 장식이다 — 9행 모두 선다", () => {
    for (const text of atThreePlaces(";-;")) {
      expect(assess(text), text).toEqual(PLANNED_STATEMENT_VERDICT);
    }
  });

  it("얼굴이 아닌 대조 45행은 원래대로 서지 않는다", () => {
    expect(NON_SEPARATOR_FACE_ROWS).toHaveLength(45);
    expect(NON_SEPARATOR_FACE_ROWS.filter((text) => !sameAsBase(text))).toEqual([]);
  });

  it("말줄임(`...`·U+2026·U+2025)은 얼굴이 아니다 — 문장은 선다", () => {
    for (const mark of ["...", "\u{2026}", "\u{2025}", "....", "--"]) {
      for (const text of atThreePlaces(mark)) {
        expect(assess(text), text).toEqual(PLANNED_STATEMENT_VERDICT);
      }
    }
  });

  it("정규화가 접는 U+037E·U+203C — 규칙은 못 보고, 두 입구는 `;`·`!!` 를 쓴 문장과 같게 판정한다", () => {
    expect("\u{37E}".normalize("NFC")).toBe(";");
    expect(normalizeAmoraSafetyText("\u{203C}\u{FE0F}")).toBe("!!");
    expect(NORMALISER_FOLDED_ROWS).toHaveLength(18);
    for (const text of NORMALISER_FOLDED_ROWS) {
      const folded = normalizeAmoraSafetyText(text);
      expect(assess(text), text).toEqual(assess(folded));
      expect(classifyAmoraCrisis(text), text).toEqual(classifyAmoraCrisis(folded));
    }
  });

  it("두 입구가 같은 판정을 낸다 — 원문과 정규화본(이 파일의 모든 행 + 이 절의 행)", () => {
    const rowsToCheck = [
      ...EVERY_ROW,
      ...SEPARATOR_FACE_ROWS,
      ...NON_SEPARATOR_FACE_ROWS,
      ...NORMALISER_FOLDED_ROWS,
    ];
    const disagree = rowsToCheck.filter(
      (text) => !isDeepStrictEqual(assess(text), assess(normalizeAmoraSafetyText(text))),
    );
    expect(disagree).toEqual([]);
  });

  it("호환 자모로 친 `하`(U+314E U+314F) — 원문을 받는 입구도 선다", () => {
    for (const text of ["죽으려고 \u{314E}\u{314F}고 있어", "오늘 죽으려고 \u{314E}\u{314F}고 있어"]) {
      expect(normalizeAmoraSafetyText(text), text).toContain("하고 있어");
      expect(assess(text), text).toEqual(PLANNED_STATEMENT_VERDICT);
      expect(classifyAmoraCrisis(text)?.kind, text).toBe("self_harm");
    }
  });

  it("다짐이 굳은 임박상은 선다 — `이미 죽으려고 마음먹었어` · 1인칭 `나 벌써 죽으려고 준비했어`", () => {
    for (const text of ["이미 죽으려고 마음먹었어", "나 벌써 죽으려고 준비했어", "이미 죽으려고 결심했어요", "모든 게 이미 죽으려고 정했어"]) {
      expect(assess(text), text).toEqual(PLANNED_STATEMENT_VERDICT);
    }
  });
});
