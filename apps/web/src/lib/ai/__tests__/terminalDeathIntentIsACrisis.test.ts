type ArchiveExpectation = "catch" | "engage" | "third" | "notself" | "pass" | "miss";
interface ArchiveGroup {
  label: string;
  expectation: ArchiveExpectation;
  rows: readonly string[];
}
const ARCHIVE: ArchiveGroup[] = [];
let archiveLabel = "";
function archive(label: string, body: () => void): void {
  archiveLabel = label;
  body();
}
function rows(list: readonly string[], expectation: ArchiveExpectation): void {
  ARCHIVE.push({ label: archiveLabel, expectation, rows: list });
}

