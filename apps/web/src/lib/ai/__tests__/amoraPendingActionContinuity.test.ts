import { describe, expect, it } from "vitest";
import { hasNewAmoraChangeIntent } from "../amoraPendingActionContinuity";

describe("새 변경 요청과 기존 확인 카드의 연속성을 구분한다", () => {
  it.each([
    "신혼여행 예산은 801만 원, 예비비·사용처 미정은 200만 원으로 배분해줘. 두 항목만 반영하고 기존 총예산, 나머지 항목, 기록 지출과 분담은 유지해줘. 적용할 변경 내용을 먼저 보여줘.",
    "총예산을 3500만원으로 바꿔줘.",
    "2026년 10월 10일 드레스 투어 일정을 추가해줘.",
    "사진 예산을 300만원으로 수정해 주세요.",
    "신혼여행에 801만원을 배정해줘.",
    "예비비를 200만원으로 잡아줘.",
    "예산을 사진 300만원과 드레스 200만원으로 분배해줘.",
    "사진 예산을 300만원으로 설정해줘.",
    "맞춤 예산만 150만원에서 151만원으로 수정하고 싶어.",
    "아까 제안은 취소해줘.",
    "첫 번째 준비 항목을 완료 처리해줘.",
    "일정은 저장하지 말고 예산을 5000만원으로 변경해줘.",
  ])("별도 변경을 요청하면 이전 카드를 쉬게 한다: %s", text => {
    expect(hasNewAmoraChangeIntent(text)).toBe(true);
  });

  it.each([
    "현재 결혼 예산 확인 내용을 설명해줘",
    "이 변경 내용을 설명해줘.",
    "저장하지 말고 예산을 알려줘.",
    "신혼집 이사 비용 때문에 부부 재정을 어떻게 나눌지 대화하고 싶어",
    "응, 그렇게 해줘",
    "이대로 적용해줘",
    "기존 제안대로 반영해 주세요.",
    "예산 3000만원을 제안한 이유가 뭐야?",
  ])("설명과 기존 제안에 대한 짧은 동의는 새 변경이 아니다: %s", text => {
    expect(hasNewAmoraChangeIntent(text)).toBe(false);
  });
});
