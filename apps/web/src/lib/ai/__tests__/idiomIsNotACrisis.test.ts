// @vitest-environment node

/**
 * `아파 죽겠어` 는 관용구다. 그 말을 위기로 읽으면 **사용자가 쓴 글이 사라진다.**
 *
 * 앞선 PR(`reporterPronounNeedsABoundary`)이 1인칭 대명사의 **부분일치**를 막았다
 * (`나오면`·`저녁`·`전화` 안의 `나`·`저`·`전`). 그런데 대명사가 진짜 1인칭일 때는
 * 그 경계가 아무것도 안 한다 — `나 다리 아파 죽겠어` 의 `나` 는 진짜 `나` 다.
 * 제3자 전언(`엄마가 무릎 아파 죽겠대`)도 마찬가지다.
 *
 * ## 무엇을 고쳤나
 *
 * 세 갈래를 무른다. 전부 **그 문장에 다른 위기 신호가 없을 때만** 적용한다.
 *
 * 1. `<원인 서술어> 죽겠` (`아파 죽겠`·`설레 죽겠`) — 관용구
 * 2. 약이 **떨어졌다**는 뜻의 `다 먹었다` (`진통제 다 먹었는데도 …`)
 * 3. 자해 표현이 든 절이 **전부** 부정형 (`죽고 싶다는 생각은 해본 적 없어`)
 *
 * ## 측정 (base = `origin/main` = 운영 배포본, 같은 코퍼스로 나란히)
 *
 * 코퍼스 309문장 — 저장소 launch 코퍼스 63 + 앞선 PR 56 + **이 수정을 보지 않은
 * 에이전트가 따로 만든 190**. 관문은 실제 관문 둘의 합집합
 * (`classifyAmoraCrisis` 또는 `hasAmoraSafetySignal`).
 *
 *     오탐   base 43/175  →  이후 0/175
 *     미탐   base 50/134  →  이후 50/134   (변화 없음)
 *     잃은 양성 0 · 새 오탐 0
 *
 * **미탐 50건은 이 수정이 만든 것이 아니라 원래 있던 것이다.** 옥상·수면제 한 통·
 * 마지막 편지·갈비뼈·흉기 같은 진짜 위험을 안전망이 그대로 지나친다. 그건 이
 * 수정의 범위가 아니라 다음 작업이고, 이 파일은 **그 수를 늘리지 않았다는 것**만
 * 증명한다.
 *
 * ## 아래 "반드시 잡아야" 절반은 내가 만든 회귀를 잡은 문장이다
 *
 * 독립 코퍼스 309문장으로는 회귀 0이었는데, 무름을 악용하는 조합을 손으로 지어
 * 돌리니 **세 건이 깨져 있었다.** 코퍼스에 그 조합이 없었을 뿐이다. 그 세 문장이
 * 아래에 있고, 지우면 같은 회귀가 조용히 돌아온다.
 */
import { describe, expect, it } from "vitest";
import { classifyAmoraCrisis } from "@/lib/ai/amoraCrisisSafety";
import { hasAmoraSafetySignal } from "@/lib/ai/amoraQuestionScope";

/** 실제 관문. 둘 중 하나라도 서면 그 메시지는 안전 경로로 간다. */
const engages = (text: string) =>
  classifyAmoraCrisis(text) !== null || hasAmoraSafetySignal(text);

describe("관용구를 위기로 읽지 않는다", () => {
  it.each([
    // 1인칭 주어가 **진짜** 1인칭인 관용구. 경계로는 못 거른다.
    "웨딩홀 세 군데 돌았더니 나 다리 아파 죽겠어",
    "저 축의금 정리하느라 손목 아파 죽겠어요",
    "내가 요즘 청첩장 때문에 바빠 죽겠어",
    // 제3자 전언 + 관용구.
    "엄마가 예단 준비하느라 무릎 아파 죽겠대",
    "언니가 본인 결혼식 때 하객 정리하느라 힘들어 죽겠다고 했어",
    "신랑이 예단 얘기만 나오면 답답해 죽겠다고 해",
    "친구가 우리 예식장 좋다고 부러워 죽겠대",
    "축가 부탁한 친구가 연습하느라 목 아파 죽겠다고 하네",
    "엄마가 결혼식 준비 힘들어 죽겠다고 하시는데 뭘 덜어드릴까",
    // 약이 떨어졌다는 뜻.
    "진통제 다 먹었는데도 드레스 투어는 다녀왔어",
    "감기약 다 먹었는데도 기침이 안 멎어서 본식이 걱정돼",
    // 자해 표현이 전부 부정형.
    "결혼 준비가 힘들긴 해도 죽고 싶다는 생각은 해본 적 없어",
  ])("%s", (text) => {
    expect(engages(text), "평범한 문장을 안전 경로로 보냈다 — 사용자가 쓴 글이 사라진다").toBe(false);
  });
});

describe("무름이 진짜 위기를 덮지 않는다", () => {
  it.each([
    // 관용구 모양이면서 진짜 자해 진술. 같은 문장의 다른 신호가 무름을 되무른다.
    "본식 준비가 힘들어 죽겠고 진짜로 죽어버리고 싶어요",
    "배고파 죽겠어 나 죽을래",
    "힘들어 죽겠어 자살하고 싶어",
    "답답해 죽겠어 남편이 칼 들고 협박했어",
    // **여기 셋이 내가 만든 회귀를 잡았다.** 독립 코퍼스는 통과시켰다.
    "자해한 적 없어요 그런데 오늘 손목을 그었어요",
    "감기약 다 먹었는데도 안 나아 그리고 수면제 한 통 먹었어",
    "진통제 다 먹었는데도 아파서 번개탄을 사 왔어",
    // 부정이 앞 절에만 있고 뒤 절은 진짜 고백.
    "죽고 싶다는 생각은 해본 적 없어 근데 어제 자해했어",
  ])("%s", (text) => {
    expect(engages(text), "진짜 위기를 관용구로 읽고 지나갔다").toBe(true);
  });
});
