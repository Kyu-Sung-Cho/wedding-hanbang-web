/**
 * 1인칭 대명사가 다른 낱말의 첫 음절에 걸려 평범한 문장이 자해 위기가 되지 않는가.
 *
 * `REPORTER_ACTOR_PATTERN` 이 `(?:나|난|나는|내가|나도|저|전|저는|제가|저도)` 였다.
 * 경계가 없어서 `나`가 `나오`·`나가`·`나중`·`나머지`·`나이`·`나눠` 의 첫 음절에,
 * `저`가 `저녁`·`저번`·`저희`·`저쪽` 에, `전`이 `전화`·`전부`·`전세`·`전날` 에,
 * `난`이 `난방` 에 걸렸다. 그 자리는 `.{0,32}` 뒤의 `죽겠` 와 묶여 자해 진술이 되므로
 * **"예단 얘기만 나오면 답답해 죽겠음" 이 자해 위기로 판정됐다.**
 *
 * ## 대가가 경고 한 줄이 아니다
 *
 * 위기로 판정되면 `planAmoraCrisisDelivery` 가 `local_safety_hold` 를 내고,
 * `/api/chat/messages` 는 저장 전에 반환한다. 작성창은 복구 없이 비워지고 첨부는
 * 전송되지 않는다 — **사용자가 쓴 글이 사라지고** 자살 상담 전화번호 카드가 나간다.
 *
 * ## 측정 (옛 상수를 임시로 되돌려 나란히 비교)
 *
 *     겨냥해 만든 평범한 문장 20개   이전 20건 걸림 → 이후 0건
 *     반드시 잡아야 할 자해 17문장   이전 2건 놓침 → 이후 2건 놓침 (동일)
 *     독립 구축 양성 코퍼스 138문장  이전 10건 탐지 → 이후 10건 탐지 (동일)
 *
 * 재현율은 한 건도 잃지 않았다. 낱말을 하나씩 제외하지 않은 이유는 `나`로 시작하는
 * 한국어 낱말에 끝이 없기 때문이고, 대신 **조사를 달거나 경계에서 끝나야 한다**는
 * 형태 규칙으로 막았다. 같은 파일의 `EXPLICIT_REPORTER_ACTOR_PATTERN` 이 이미 쓰던
 * 방식이다.
 */
import { describe, expect, it } from "vitest";
import { assessAmoraSafetyText } from "@hanbang/shared/amora-crisis-classifier";

const isCrisis = (text: string) =>
  assessAmoraSafetyText(text).resolution === "immediate_crisis";

/** 결혼 준비 대화의 평범한 문장. 하나라도 위기면 사용자의 글이 사라진다. */
const EVERYDAY = [
  // 나오 / 나가 / 나중 / 나머지 / 나이 / 나눠
  "예단 얘기만 나오면 답답해 죽겠음",
  "그 얘기만 나오면 죽겠어",
  "견적서 나오면 또 싸울 것 같아 죽겠다",
  "사진 원본 나오려면 한 달이라는데 답답해 죽겠네",
  "밖에 나가면 더워 죽겠어",
  "나중에 정산하려니 머리 아파 죽겠어",
  "나머지 항목은 언제 정하냐고 물어봐서 귀찮아 죽겠다",
  "나이 얘기 나올 때마다 민망해 죽겠어",
  "청첩장 시안 나오면 바로 알려줘 궁금해 죽겠네",
  "드레스 나오는 날만 기다려서 설레 죽겠어",
  "나눠서 결제하려니까 계산이 복잡해 죽겠다",
  // 저녁 / 저번 / 저희 / 저쪽
  "저녁 메뉴 고르다 배고파 죽겠어",
  "저번에 간 웨딩홀 별로여서 답답해 죽겠다",
  "저희 부모님 의견 맞추느라 힘들어 죽겠어요",
  "저쪽 업체가 연락을 안 줘서 답답해 죽겠네",
  // 전화 / 전부 / 전세 / 전날
  "전화가 계속 와서 정신없어 죽겠어",
  "전부 다시 해야 한다니 막막해 죽겠다",
  "전세 알아보느라 바빠 죽겠어",
  "전날 리허설까지 있어서 피곤해 죽겠네",
  // 난방
  "난방비까지 생각하니 계산이 복잡해 죽겠어",
];

/** 진짜 자해 진술. 경계를 넣어도 계속 잡혀야 한다. */
const REAL_DISCLOSURE = [
  "나 진짜 죽고 싶어",
  "난 죽고 싶어",
  "나는 죽고 싶어요",
  "나도 죽고 싶다는 생각이 들어",
  "저 죽고 싶어요",
  "전 자해하고 있어요",
  "저는 목숨을 끊고 싶어요",
  "저도 죽고 싶어요",
  "제가 자해했어요",
  "나, 죽고 싶어",
  "저... 죽고 싶어요",
  "나 목숨을 끊으려고 해",
  "나한테 자해 충동이 계속 와요",
  "저에게 죽고 싶은 마음이 자꾸 들어요",
];

describe("1인칭 대명사는 경계를 요구한다", () => {
  it.each(EVERYDAY)("평범한 문장이 위기가 되지 않는다: %s", (text) => {
    expect(isCrisis(text)).toBe(false);
  });

  it.each(REAL_DISCLOSURE)("진짜 자해 진술은 그대로 잡는다: %s", (text) => {
    expect(isCrisis(text)).toBe(true);
  });

  it("경계 규칙이 조사는 허용하고 다른 낱말은 막는다", () => {
    // 조사가 붙은 대명사는 주어다.
    for (const text of ["나는 죽고 싶어", "나도 죽고 싶어", "저는 죽고 싶어요"]) {
      expect(isCrisis(text)).toBe(true);
    }
    // 같은 음절로 시작하지만 다른 낱말이면 주어가 아니다.
    for (const text of ["나오면 죽겠어", "저녁에 죽겠어", "전부 죽겠어"]) {
      expect(isCrisis(text)).toBe(false);
    }
  });
});
