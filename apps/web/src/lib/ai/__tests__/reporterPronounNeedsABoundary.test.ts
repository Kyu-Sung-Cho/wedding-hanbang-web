/**
 * 평범한 문장이 자해 위기로 판정돼 사용자가 쓴 글이 사라지지 않는가.
 *
 * `죽겠다` 는 한국어에서 가장 흔한 강조 표현이다. 그런데 1인칭 주어 패턴에 경계가
 * 없어서 `나` 가 `나오`·`나가`·`나중`·`나머지`·`나이`·`나눠` 의 첫 음절에, `저` 가
 * `저녁`·`저번`·`저쪽` 에, `전` 이 `전화`·`전부`·`전세`·`전날` 에, `난` 이 `난방` 에,
 * `제가` 가 `문제가`·`숙제가`·`언제가` 안에 걸렸다. 그 자리는 `.{0,32}` 뒤의 `죽겠`
 * 와 묶여 자해 진술이 된다:
 *
 *     드레스 나오는 날만 기다려서 설레 죽겠어   → 자해 위기
 *     저녁 메뉴 고르다 배고파 죽겠어           → 자해 위기
 *     문제가 생겨서 답답해 죽겠어              → 자해 위기
 *
 * 그 판정의 대가는 경고 한 줄이 아니다. `planAmoraCrisisDelivery` 가
 * `local_safety_hold` 를 내면 `/api/chat/messages` 가 저장 전에 반환하고, 작성창은
 * 복구 없이 비워지며 첨부는 삭제된다 — **사용자가 쓴 글이 사라진다.**
 *
 * ## 경계를 통째로 씌우면 진짜 자해를 잃는다
 *
 * 처음에는 1인칭 주어 패턴 자체에 경계를 씌웠다. 적대적 감사가 blocker 를 냈다 —
 * 한국어는 조사를 겹쳐 쓰고(한테+도, 는+요) 1인칭에 `저희` 도 쓰는데, 조사 한 칸만
 * 허용한 패턴이 "나한테도 자해 충동이 와요"·"저희도 목숨을 끊는 얘기를 했어요" 를
 * 놓쳤다. 게다가 잃은 문장은 파트너 레인에서 `bride_private` → `shared` 로 돌아가
 * **자해 고백이 배우자에게 보이게** 됐다.
 *
 * 그래서 **동사를 세기로 갈랐다.** 관용 용법이 없는 강한 동사(`자살`·`자해`·
 * `목숨을 끊`·`죽고 싶`·`사라지고 싶`)는 느슨한 주어를 그대로 쓰고, 관용으로도
 * 쓰이는 약한 동사(`죽겠`·`죽을 래/거`)만 경계를 요구하는 주어를 쓴다.
 *
 * ## 측정 (파일 전체를 origin/main 으로 임시 되돌려 문장 단위 대조)
 *
 *     자연 위기 진술 20문장   잃음 0 · 얻음 0
 *     독립 구축 양성 138문장  잃음 0 · 얻음 0
 *     독립 구축 음성 110문장  오탐 1건 제거 · 새 오탐 0
 *     겨냥해 만든 평범한 문장 30개   이전 20건 걸림 → 이후 0건
 */
import { describe, expect, it } from "vitest";
import { classifyAmoraCrisis } from "@/lib/ai/amoraCrisisSafety";
import { hasAmoraSafetySignal } from "@/lib/ai/amoraQuestionScope";

/** 실제 관문. 둘 중 하나라도 참이면 사용자의 글이 사라진다. */
const gated = (text: string) =>
  Boolean(classifyAmoraCrisis(text)) || hasAmoraSafetySignal(text, "chat");

/** 결혼 준비 대화의 평범한 문장. 하나라도 위기면 사용자의 글이 사라진다. */
const EVERYDAY = [
  // 나오 / 나가 / 나중 / 나머지 / 나이 / 나눠
  "예단 얘기만 나오면 답답해 죽겠음",
  "그 얘기만 나오면 죽겠어",
  "견적서 나오면 또 싸울 것 같아 죽겠다",
  "사진 원본 나오려면 한 달이라는데 답답해 죽겠네",
  "밖에 나가면 더워 죽겠어",
  "나중에 정산하려니 머리 아파 죽겠어",
  "나머지 항목은 언제 정하냐고 물어봐서 귀찮아 죽겠다",
  "나이 얘기 나올 때마다 민망해 죽겠어",
  "청첩장 시안 나오면 바로 알려줘 궁금해 죽겠네",
  "드레스 나오는 날만 기다려서 설레 죽겠어",
  "나눠서 결제하려니까 계산이 복잡해 죽겠다",
  // 저녁 / 저번 / 저희 / 저쪽
  "저녁 메뉴 고르다 배고파 죽겠어",
  "저번에 간 웨딩홀 별로여서 답답해 죽겠다",
  "저희 부모님 의견 맞추느라 힘들어 죽겠어요",
  "저쪽 업체가 연락을 안 줘서 답답해 죽겠네",
  // 전화 / 전부 / 전세 / 전날
  "전화가 계속 와서 정신없어 죽겠어",
  "전부 다시 해야 한다니 막막해 죽겠다",
  "전세 알아보느라 바빠 죽겠어",
  "전날 리허설까지 있어서 피곤해 죽겠네",
  // 난방
  "난방비까지 생각하니 계산이 복잡해 죽겠어",
  // 대명사 **앞** 경계 — 문제가·숙제가·언제가 안의 "제가"
  "문제가 생겨서 답답해 죽겠어",
  "숙제가 밀려서 짜증나 죽겠다",
  "언제가 좋을지 몰라서 답답해 죽겠네",
  "이 문제가 계속 나와서 미치겠어 죽겠다",
  "문제가 나서 죽겠어",
  // 조사 반복을 허용할 때 새로 열리는 자리
  "일이 자꾸 나서 죽겠다",
  "나로 인해 늦어져서 미안해 죽겠어",
  "화가 나요 진짜 죽겠어",
  "저로 인한 일은 아니라 다행이라 죽겠네",
  "전요 이 홀이 제일 좋아서 설레 죽겠어요",
];

/**
 * 진짜 자해·위기 진술. 전부 계속 잡혀야 한다.
 *
 * 아래 절반은 **적대적 감사가 "경계를 통째로 씌웠더니 잃었다"고 확정한 문장들**이다.
 * 조사를 겹쳐 쓰거나(한테+도, 는+요) `저희` 를 쓰는 형태라, 이 목록이 없으면 같은
 * 회귀를 다시 만든다.
 */
const REAL_DISCLOSURE = [
  // 흔한 형태
  "나 진짜 죽고 싶어",
  "난 죽고 싶어",
  "나는 죽고 싶어요",
  "나도 죽고 싶다는 생각이 들어",
  "저 죽고 싶어요",
  "전 자해하고 있어요",
  "저는 목숨을 끊고 싶어요",
  "저도 죽고 싶어요",
  "제가 자해했어요",
  "나 죽을래",
  "저 죽을 거예요",
  "내가 손목을 그었어",
  // 감사가 확정한 손실 — 조사 겹침·저희·는요
  "나한테도 자해 충동이 와요",
  "저번 주에 자해했어요",
  "저한텐 자해 충동이 계속 있어요",
  "나는요 오늘 죽을 거예요",
  "저희도 목숨을 끊는 얘기를 했어요",
  "나는요 어제 자해했어요",
  "저에겐 목숨을 끊는 것밖에 없어요",
  "저희 둘 다 자해했어요",
  // 자해 아닌 갈래 — 이 상수를 함께 쓰는 규칙들
  "저희 남편을 지금 죽이러 갈 거예요",
  "나는요 친구가 자해한다고 들었어요",
  "저는요 지금 남편 목을 조르는 중이에요",
  "저는요 동생이 자해한다고 해서 무서워요",
  "내가요 친구가 자살한다고 해서 놀랐어요",
  "저희 남편을 죽이고 저도 죽을 거예요",
];

describe("1인칭 대명사는 경계를 요구한다 — 약한 동사에 한해", () => {
  it.each(EVERYDAY)("평범한 문장이 위기가 되지 않는다: %s", (text) => {
    expect(gated(text)).toBe(false);
  });

  it.each(REAL_DISCLOSURE)("진짜 위기 진술은 그대로 잡는다: %s", (text) => {
    expect(gated(text)).toBe(true);
  });

  it("강한 동사는 경계를 요구하지 않는다", () => {
    // 이 구분이 이 수정의 핵심이다. `자해` 는 관용 용법이 없어서 주어를 느슨하게
    // 잡아도 평범한 문장을 끌어오지 않고, 그래서 조사 겹침에도 살아남는다.
    expect(gated("저한텐 자해 충동이 계속 있어요")).toBe(true);
    // `죽겠` 는 강조 표현이라 경계를 요구한다.
    expect(gated("저녁 메뉴 고르다 배고파 죽겠어")).toBe(false);
  });

  it("요는 다른 조사 뒤에만 붙는다", () => {
    // "나는요" 는 나+는+요 지만 "나요" 는 동사 나다의 활용이다.
    expect(gated("나는요 오늘 죽을 거예요")).toBe(true);
    expect(gated("화가 나요 진짜 죽겠어")).toBe(false);
  });
});
