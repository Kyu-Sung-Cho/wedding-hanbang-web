import { describe, expect, it } from "vitest";

import { classifyAmoraQuestionScope, hasAmoraSafetySignal } from "../amoraQuestionScope";

/**
 * **맨 `협박` 갈래가 평범한 결혼 문장을 안전 레인으로 보내던 것을 막는다.**
 *
 * `a6e374c15`(2026-08-31)가 목적어 없는 협박 고백을 잡으려고 맨 `협박` 을 신호로
 * 넣었다. 의도는 옳았다 — 한국어는 목적어를 생략하고, 실측상 첫 고백 여덟 중
 * 일곱이 협박하는 배우자가 읽는 `shared` 레인에 저장되고 있었다.
 *
 * 그런데 그 커밋의 음성 코퍼스는 `~다고 협박`(전언) 틀만 겨냥했다. 화자가 스스로
 * 무르는 비유 표현("협박 비슷한", "협박하듯", "협박처럼")과 화제 명사 용법
 * ("협박 기사", "협박 후기")은 한 번도 밟히지 않았고, 저장소 테스트 9,200개가
 * 전부 초록인 채로 배포됐다.
 *
 * 세 판본을 같은 코퍼스로 나란히 재서 확인한 값(2026-09-02):
 *
 *     8-31 커밋 이전     오탐  1/18 · 미탐 4/8
 *     8-31 커밋(배포됨)   오탐 15/18 · 미탐 1/8    <- 오탐을 14개 새로 만들었다
 *     현재               오탐  3/18 · 미탐 0/8
 *
 * 배포본보다 양쪽 다 낫고, 커밋 이전보다 미탐이 4→0이다. 그 대가로 오탐이
 * 1→3인데, 남은 셋은 아래에 이유와 함께 적어 두었다.
 *
 * **낱말로 다 풀리지 않는다.** 진짜 해법은 어휘가 아니라 행위자 결속이고,
 * 더 근본적으로는 "비공개 레인에 넣기"와 "112·119 안내 + 도구 제거"가 한
 * 신호에 묶여 있는 구조다 — 두 판단은 틀렸을 때의 대가가 정반대다.
 * 그건 파운더 판단 사안이라 여기서 건드리지 않았다.
 */

// 안전 레인으로 가면 안 되는 평범한 결혼 문장.
const ORDINARY = [
  // 화자가 스스로 무르는 비유 — 이 갈래를 정면으로 겨냥한다.
  "예단 문제로 협박 비슷한 말을 들었어요",
  "시어머니가 협박하듯 말씀하셔서 속상해요",
  "웨딩홀 상담에서 거의 협박 수준으로 계약을 밀어붙였어요",
  "협박당하는 기분이 들 정도로 예단 얘기가 심해요",
  "친정에서 협박처럼 느껴지는 말을 해서 힘들어요",
  "예산 얘기만 나오면 협박하는 것 같아서 대화가 안 돼요",
  "상견례 자리에서 협박에 가까운 농담이 오갔어요",
  "협박이라고 하기엔 뭐하지만 압박이 심해요",
  "드레스 계약 안 하면 안 된다고 협박처럼 얘기하더라고요",
  "협박까지는 아니고 그냥 서운한 얘기였어요",
  // 협박이 화제 명사로 쓰인 경우 — 나에게 일어난 일이 아니다.
  "요즘 웨딩 업계 협박 기사 보셨어요?",
  "협박 관련해서 법적으로 어떻게 되나요?",
  "결혼 준비 카페에 협박 후기 글이 올라왔더라고요",
  // 제3자·비유가 아닌 평범한 문맥.
  "요즘 결혼 준비하면서 협박 아닌 잔소리를 많이 들어요",
  "부모님 협박에 못 이겨 예식장을 바꿨어요",
];

/**
 * 아직 안전 레인으로 가는 것들. **고쳐야 할 것으로 알고 남긴다.**
 * 여기서 빠지면(=고쳐지면) 아래 테스트가 알려준다.
 */
const KNOWN_FALSE_POSITIVES = [
  // 위기 분류기(packages/shared)가 잡는다. 8-31 커밋 이전에도 똑같이 걸렸으므로
  // 이 갈래가 만든 것이 아니다.
  "축의금 문제로 협박 아닌 협박을 받았어요",
  // 진짜 가족 압박일 수 있어 안전 쪽으로 두는 편이 낫다고 판단했다.
  "예단 협박 때문에 스트레스가 심해요",
  // `농담` 을 무름에 넣으면 "죽인다고 협박해 놓고 농담이래요" 가 같이 풀린다.
  "친구가 축의금 협박한다고 농담해요",
];

// 반드시 안전 레인으로 가야 하는 것. 이 갈래가 존재하는 이유다.
const REAL_DANGER = [
  "신랑이 저를 협박해요",
  "예비 남편이 협박하면서 무섭게 굴어요",
  "남편이 헤어지면 가만 안 둔다고 협박해요",
  "신랑이 저한테 협박을 계속해서 무서워요",
  "예비신랑이 협박해서 신고하고 싶은데 무서워요",
  "약혼자가 저를 협박하고 있어요",
  "남자친구가 협박하듯 때린다고 했어요",
  "신랑이 협박처럼 죽인다고 말했어요",
];

const safetyOf = (userText: string) => hasAmoraSafetySignal(userText);

describe("목적어 없는 협박 고백", () => {
  it.each(ORDINARY)("평범한 결혼 문장은 안전 레인으로 가지 않는다: %s", (text) => {
    expect(safetyOf(text)).toBe(false);
  });

  it.each(REAL_DANGER)("협박받는 고백은 안전 레인으로 간다: %s", (text) => {
    expect(safetyOf(text)).toBe(true);
  });

  it("아직 못 고친 오탐 목록이 정확하다 — 늘어도 줄어도 알려준다", () => {
    // 줄어들면(고쳐지면) 이 목록에서 빼라. 늘어나면 회귀다.
    const stillLeaking = KNOWN_FALSE_POSITIVES.filter(safetyOf);
    expect(stillLeaking).toEqual(KNOWN_FALSE_POSITIVES);
  });

  it("비유를 무르는 것이 진짜 신체 위험까지 무르지는 않는다", () => {
    // `협박하듯`·`협박처럼` 은 무름 대상이지만, 전해진 내용이 신체 위험이면
    // 그 무름이 다시 무효가 되어야 한다.
    expect(safetyOf("남자친구가 협박하듯 때린다고 했어요")).toBe(true);
    expect(safetyOf("신랑이 협박처럼 죽인다고 말했어요")).toBe(true);
  });

  it("W2 로 갈 때 사유는 safety 다 — domain 으로 새면 안내가 달라진다", () => {
    const c = classifyAmoraQuestionScope({ userText: "신랑이 저를 협박해요" });
    expect(c.scope === "W2_high_risk_adjacent" || c.scope === "W5_safety_override").toBe(true);
    if (c.scope === "W2_high_risk_adjacent") expect(c.highRiskReason).toBe("safety");
  });
});
