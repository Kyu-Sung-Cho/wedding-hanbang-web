/**
 * 2026-08-29 적대적 검토(4개 렌즈 · 23개 지적 · 16개 재현 확인)가 잡아낸 것들.
 *
 * 이 파일의 문장은 전부 **실제로 재현된** 것이고, 검토가 origin/main 과 대조해
 * 이 브랜치가 만든 회귀임을 확인한 것들이다. 고친 방식이 아니라 **사용자에게
 * 보이는 결과**를 고정한다.
 */
import { describe, expect, it } from "vitest";

import { classifyAmoraQuestionScope } from "@/lib/ai/amoraQuestionScope";

const c = (userText: string) => classifyAmoraQuestionScope({ userText });
const nl = String.fromCharCode(10);
const notW0 = (list: readonly string[]) =>
  list.filter((t) => c(t).scope === "W0_wedding_core").join(nl);
const isW0 = (list: readonly string[]) =>
  list.filter((t) => c(t).scope !== "W0_wedding_core")
    .map((t) => `${c(t).scope} | ${t}`).join(nl);

describe("결혼 낱말을 심어 다른 분야 울타리를 열 수 없다", () => {
  // WEDDING_STATE_PHRASE_PATTERN 은 문장 전체를 보므로, 결혼명사+상태명사 쌍이
  // 어디에 있든 EXPLICIT_NON_WEDDING_STATE 울타리가 통째로 꺼졌다. 33/33, 72/72 재현.
  it("결혼을 명시적으로 배제한 문장이 결혼 도구를 받지 않는다", () => {
    expect(notW0([
      "결혼 일정 말고 회사 일정 내일로 추가해줘",
      "우리 결혼 일정 말고 회사 프로젝트 일정 알려줘",
      "회사 예산 알려줘 결혼 예산도 봐줘.",
      "결혼 일정 겸 회사 체크리스트 알려줘",
      "회사 일정 알려줘 웨딩 예약도 있어.",
      "이건 결혼 일정 얘기야. 회사 일정을 추가해줘",
      "웨딩 예약 확인했어. 회사 회식 일정 추가해줘",
      "청첩장 일정 정리해줘. 그리고 병원 예약도 잡아줘",
    ])).toBe("");
  });

  it("공유 장기 기억도 열리지 않는다", () => {
    // 진짜 대가는 도구가 아니라 기억이다.
    const opened = [
      "결혼 일정 말고 회사 일정 내일로 추가해줘",
      "회사 예산 알려줘 결혼 예산도 봐줘.",
    ].filter((t) => c(t).allowsLongTermMemory);
    expect(opened.join(nl)).toBe("");
  });
});

describe("예산 관문은 말의 첫머리에서만 열린다", () => {
  it("문장 중간에서 시작하는 우회가 막힌다", () => {
    // 절 첫머리(`[.!?]\s*예산`)를 허용했더니 100건 중 76건이 열렸다.
    expect(notW0([
      "자퇴할까 고민중. 예산 짜줘",
      "게임기 사려고. 예산 짜줘",
      "도박 빚 갚아야 해. 예산 정리해줘",
      "논문 써야 하는데. 예산 얼마 남았어?",
      "문신 지우려고! 예산 알려줘",
    ])).toBe("");
  });

  it("허용 앞말로 화제를 감출 수 없다", () => {
    // 허용 목록 낱말을 앞에 붙이면 필터가 통째로 꺼졌다.
    expect(notW0([
      "자퇴하려는데 우리 예산 짜줘",
      "게임기 사려는데 전체 예산 짜줘",
      "자퇴 관련해서 그럼 예산 짜줘",
      "우리 예산이랑 자퇴 예산 둘 다 짜줘",
      "전체 예산 말고 게임 예산 짜줘",
    ])).toBe("");
  });

  it("<화제> 예산은 그대로 막힌다", () => {
    expect(notW0([
      "자퇴 예산 짜줘", "게임 예산 보여줘", "도박 빚 예산 얼마나 잡아야 해?",
      "유튜브 예산 항목별로 정리해줘", "논문 예산 배분해줘", "육아 예산 짜줘",
    ])).toBe("");
  });
});

describe("사람들이 실제로 쓰는 예산 문장은 열린다", () => {
  it("앱 자신의 예산 카테고리 이름이 붙어도 열린다", () => {
    // 앞 낱말 검사 필터가 이 11개를 전부 끊었다. 사용자는 "제가 도울 범위가
    // 아니에요" 를 받았다.
    expect(isW0([
      "사진 예산 알려줘", "영상 예산 알려줘", "음식 예산 얼마야?",
      "꽃 예산 알려줘", "식비 예산 얼마로 잡아야 해?", "가전 예산 알려줘",
      "주차 예산 얼마 잡아야 해?", "생화 예산 좀 알려줘",
      "사진 예산 항목 하나 완전히 삭제해줘", "사진 예산표 보여줘",
    ])).toBe("");
  });

  it("두 낱말 꾸밈말이 막히지 않는다", () => {
    expect(isW0([
      "이번 달 예산 얼마 남았어?", "저번 주 예산 얼마 썼어?",
      "지난달 예산 얼마 썼는지 보여줘", "지금까지 쓴 예산 알려줘",
      "우리 둘 예산 얼마야?", "전체적인 예산 알려줘",
      "월별 예산 알려줘", "카테고리별 예산 알려줘", "대략적인 예산 알려줘",
    ])).toBe("");
  });

  it("대화 시작말이 붙어도 막히지 않는다", () => {
    expect(isW0([
      "혹시 예산 얼마 남았어?", "그러면 예산 얼마 남았어?", "아 예산 얼마 남았어?",
      "그래서 예산 얼마 남았어?", "남아있는 예산 얼마야?",
    ])).toBe("");
  });

  it("예산 낱말이 같은 문장의 일정 요청을 끊지 않는다", () => {
    expect(isW0(["가전 예산 때문에 다음 주 일정 알려줘"])).toBe("");
  });

  it("신혼집 살림 일정이 끊기지 않는다", () => {
    // `이사`·`전세` 가 제외 목록에 있다는 이유로 끊겼다.
    expect(isW0([
      "전세 계약 일정 알려줘",
      "이사 날짜랑 겹치는 일정 알려줘",
      "가전 예산 500만원으로 바꿔줘",
    ])).toBe("");
  });
});

describe("가족식은 다른 낱말을 삼키지 않는다", () => {
  it("합성어는 결혼 이야기가 아니다", () => {
    expect(notW0([
      "가족식단 짜줘", "가족식탁 어디서 사?", "가족식비 얼마 들어?",
      "가족식료품 사야 해", "가족식습관 고치고 싶어", "가족식중독 조심해야지",
    ])).toBe("");
  });

  it("가족식 자체는 여전히 결혼 이야기다", () => {
    expect(isW0([
      "생각해보니 그냥 40명 정도 가족식으로 하는 게 나을 것 같아.",
      "가족식으로 바꾸면 예산이 얼마나 줄어?",
    ])).toBe("");
  });
});

describe("괴로움을 말하면 케어 레인에 남는다", () => {
  it("예산 말머리가 자해 표현을 결혼 과업으로 끌어올리지 않는다", () => {
    // W4 의 지시문은 "먼저 사람처럼 반응하세요" 다. 이 관문이 그것을 걷어냈다.
    expect(notW0([
      "예산 얘기하다가 자해 충동이 들어요",
      "그럼 예산 다시 정리하자. 다 끝내고 싶다는 생각이 들어요",
      "예산 얘기 좀 하자. 요즘 사는 게 의미가 없어",
      "예산 정리하다가 자꾸 자해 충동이 들어요",
      "우리 예산 다시 봐야 할 것 같아. 요즘 사는 게 의미가 없어",
      "예산 짜다가 자해 충동이 들 정도예요",
    ])).toBe("");
  });

  it("평범한 예산 요청까지 막지는 않는다", () => {
    // 대조군. 이게 없으면 위 검사는 "예산을 다 막는다"와 구별되지 않는다.
    expect(isW0(["예산 짜줘", "예산 얼마 남았어?"])).toBe("");
  });
});

describe("일정·할 일도 결혼 밖 화제에 열리지 않는다", () => {
  // 검토가 "기존 문제"로 분류한 것(origin/main 도 같았다). 제외 목록을 넓히면서
  // 함께 닫혔다 — main 은 이 여섯 개 전부 W0 + 기억 ON 이었다.
  it("결혼 밖 일정·할 일은 W0 이 아니다", () => {
    expect(notW0([
      "자퇴 일정 내일로 추가해줘",
      "게임 대회 일정 내일로 추가해줘",
      "도박 끊는 일정 다음주로 등록해줘",
      "논문 심사 일정 보여줘",
      "자퇴 준비 목록 보여줘",
      "유튜브 촬영 일정 알려줘",
    ])).toBe("");
  });

  it("결혼 준비 일정은 그대로 열린다", () => {
    // 대조군.
    expect(isW0([
      "드레스 피팅 일정 알려줘",
      "본식 일정 다음주로 옮겨줘",
      "청첩장 준비 목록 보여줘",
    ])).toBe("");
  });
});
