/**
 * **안전망이 그냥 지나치던 진짜 위험 118건을 잡는다.**
 *
 * 앞선 작업(`idiomIsNotACrisis`)이 오탐을 43→0 으로 줄이면서, 같은 측정이
 * **미탐 135건**을 드러냈다. 옥상에 올라와 있다는 말도, 수면제 한 통을 사 왔다는
 * 말도, 갈비뼈에 금이 갔다는 말도 안전망이 그대로 지나쳤다. 오탐보다 나쁘다 —
 * 오탐은 사용자가 다시 쓸 수 있지만, 미탐은 아무 일도 일어나지 않는다.
 *
 * ## 무엇이 없었나
 *
 * 부류로 묶으면 아홉이었다. 수단 확보(`목을 맬 끈을 찾고 있었어요`), 방법 검색,
 * 자해 흔적(`손목 그은 자국`), 위험한 장소에 지금 있음(`아파트 옥상에 올라와
 * 있어`), 완곡한 자해 의사(`죽어야 끝나겠다`), 신체 폭력(`갈비뼈에 금이 갔어`),
 * 흉기·감금·성적 강요, 한영 혼용, 그리고 **인물 목록에 시댁이 통째로 없던 것**
 * (`시어머니`·`시아버지`·`형부` 가 어느 목록에도 없었다).
 *
 * ## 넓히는 방향이라 조건을 걸었다
 *
 * 이 저장소는 안전 어휘를 넓히다 평범한 대화를 끊은 이력이 반복해 있다. 그래서
 * 모든 새 패턴이 **사람 목적어·피해·준비 동사** 중 하나를 함께 요구한다:
 *
 * - `못 나가게` 는 강아지 안전문에도 쓰인다 → 사람이 대상일 때만
 * - `주먹을 휘둘러` 는 축가 연습에도 쓰인다 → 사람이나 피해가 붙을 때만
 * - `관계를 강요` 는 독점 계약에도 쓰인다 → 사람 행위자나 거절 표시가 있을 때만
 * - `옥상`·`한강 다리` 는 예식장과 촬영지다 → 거기 있다는 서술이 붙을 때만
 * - `한 통 사 왔어` 는 두통약에도 쓰인다 → 수면제 계열만
 *
 * ## 측정 (base = 앞선 커밋, 같은 코퍼스로 나란히)
 *
 * 코퍼스 579문장 — 저장소 63 + 앞선 PR 56 + **이 수정을 보지 않은 에이전트
 * 아홉이 만든 460**(그중 270은 여기서 넣을 어휘를 겨냥해 따로 만든 반례).
 *
 *     미탐   135/234  ->  17/234
 *     오탐     2/345  ->   2/345   (변화 없음, 둘 다 이전부터 있던 것)
 *     잃은 양성 0 · 새 오탐 0
 *
 * ## 남은 17건은 낱말로 못 가린다
 *
 * `이제 그만하고 싶어`·`진짜 답이 없어`·`못 버틸 것 같아`·`정리 다 됐어` 는
 * 반례 코퍼스에 **거의 같은 문장이 평범한 뜻으로** 들어 있다("예단 얘기는 이제
 * 그만하고 싶어", "축의금 정리 다 됐어"). 어휘를 더 넣으면 그 문장들이 끊긴다.
 * 여기서 멈춘 것은 못 해서가 아니라 **대가가 더 크기 때문**이고, 이 경계를 넘으려면
 * 대화 문맥이 필요하다.
 *
 * ## 남은 오탐 둘도 그대로 적는다
 *
 * 이 수정 **이전부터** 걸리던 것이고 이번에 못 고쳤다:
 *
 *     조카가 리허설 때 신랑 머리를 때리고 도망가서 웃겼어
 *     청첩장 오타 난 거 보고 창피해서 사라지고 싶었어
 *
 * 앞의 것은 배우자 호칭 + 폭력 동사라는 기존 갈래에 걸린다. `웃겼어` 로 무르면
 * `웃으면서 때렸어요` 도 함께 무뎌진다. 뒤의 것은 `창피해서` 무름이 이 수정에서
 * 넣은 경로에는 걸리지만 기존 1인칭 갈래에는 안 걸린다. 둘 다 무르는 쪽이
 * 진짜 고백을 잃을 위험이 있어 그대로 뒀다.
 */
