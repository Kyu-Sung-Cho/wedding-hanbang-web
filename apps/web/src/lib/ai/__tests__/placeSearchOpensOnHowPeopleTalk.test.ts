import { describe, expect, it } from "vitest";

import { isPlaceSearchCandidate } from "@/lib/ai/placeSearchRouting";

/**
 * 아모라가 "검색할 수 없어요" 라고 답하는 것은 대개 사실이 아니다.
 *
 * 2026-08-26 운영 실측. 물어본 문장과 받은 답:
 *
 *     "공덕 근처 상견례 할 만한 곳 알려줘"
 *     → "공덕 근처 업체를 **직접 검색하거나 예약할 수는 없어요**."
 *
 * 네이버 지역 검색은 멀쩡히 붙어 있었고("공덕 상견례 한정식" → 한식 5/5), 질문
 * 범위도 W0 였다. 막은 것은 `isPlaceSearchCandidate` 의 가게 종류 정규식이었다 —
 * `상견례` 뒤에 `식당|장소|자리` 중 하나를 요구하는데 "상견례 **할 만한 곳**" 에는
 * 그 낱말이 없다. 도구가 목록에서 빠지면 아모라는 없는 기능이라고 말할 수밖에 없고,
 * 사용자에게는 제품이 못 하는 것으로 보인다.
 *
 * 실제 말투 13개로 재니 **5개만 열렸다.**
 *
 * ## 왜 이렇게 고쳤나
 *
 * "무엇을 파는 가게인가" 대신 **먹거나 마주 앉는 자리인가** 로 본다. 다만 조각 하나로는
 * 열지 않는다 — "곳" 만으로 열면 "드레스 볼 곳", "예식장 알아볼 곳" 까지 열리고, 그건
 * 지금 보류해 둔 업체 추천을 뒷문으로 여는 것이다.
 *
 * ## 이 테스트가 지키는 것
 *
 * 처음 잰 음성 사례 20개에서는 오탐이 0 이었다. 그런데 그 20개가 쉬웠다 — `상견례`·
 * `부모님` 과 `어디` 가 **장소가 아닌 뜻**으로 함께 오는 문장을 따로 12개 만들자
 * **7개가 열렸다.** 아래 `장소를_묻는_게_아닌_문장` 이 그 12개다. 이 목록을 줄이면서
 * 재현율을 올리는 변경은 이 테스트를 깨야 한다.
 */

const 장소를_묻는_문장 = [
  "공덕 근처 상견례 할 만한 곳 알려줘",
  "상견례 할 만한 데 어디 있을까",
  "양가 부모님 뵙기 좋은 곳 추천해줘",
  "공덕에 상견례 하기 좋은 데 알려줘",
  "상견례 어디서 하면 좋을까",
  "부모님 모시고 식사할 만한 곳 알려줘",
  "상견례 장소 추천해줘",
  "공덕 상견례 한정식 찾아줘",
  "여의도 맛집 알려줘",
  "예식장 근처 밥 먹을 곳 알려줘",
  "상견례 식당 어디가 좋아",
  "양가 상견례 자리 알아봐 줘",
  "상견례 하기 좋은 한정식 추천",
];

/** 업체 추천은 보류 중이다. 먹는 자리 어휘를 넓혔다고 여기까지 열리면 안 된다. */
const 업체를_묻는_문장 = [
  "드레스샵 추천해줘",
  "예식장 어디가 좋아",
  "스튜디오 알려줘",
  "웨딩홀 괜찮은 데 있을까",
  "메이크업샵 어디가 괜찮아",
  "본식 스냅 업체 추천",
  "신혼집 어디로 구할까",
  "신혼여행 어디가 좋을까",
];

/**
 * `상견례`·`부모님`·`어디` 가 나오지만 **장소를 묻는 게 아닌** 문장.
 * 처음 넓혔을 때 이 중 7개가 열렸다.
 */
const 장소를_묻는_게_아닌_문장 = [
  "상견례 어디까지 준비해야 해",
  "상견례 비용은 어디서 나오는 거야",
  "상견례 예절 어디서 배울 수 있어",
  "양가 부모님 의견이 어디서 갈리는지 모르겠어",
  "부모님이 어디까지 관여하시는 게 맞아",
  "상견례 때 자리 배치 어떻게 해",
  "상견례 자리에서 무슨 말을 해야 해",
  "부모님 모시고 갈 때 옷차림이 어때야 해",
  "상견례 날짜를 어디에 맞춰야 할까",
  "예단 어디까지가 보통이야",
  "양가 상견례 순서가 어떻게 돼",
  "부모님한테 결혼 이야기 어디서부터 꺼내",
];

const 관계없는_문장 = [
  "상견례 예절 알려줘",
  "상견례 때 뭐 입어야 해",
  "상견례 비용 누가 내",
  "상견례 준비물 알려줘",
  "상견례 날짜 언제가 좋을까",
  "부모님께 뭐라고 말씀드려야 할까",
  "양가 부모님 의견이 달라서 힘들어",
  "우리 예산 얼마야",
  "청첩장 언제 돌려",
  "축의금 얼마가 적당해",
  "부모님 선물 뭐가 좋을까",
  "예단은 어디까지 해야 해",
];

describe("사람이 말하는 대로 물어도 검색이 열린다", () => {
  it.each(장소를_묻는_문장)("'%s'", (question) => {
    expect(isPlaceSearchCandidate(question)).toBe(true);
  });

  it("가게 종류를 대지 않아도 열린다 — 예전엔 여기서 5/13 이었다", () => {
    const opened = 장소를_묻는_문장.filter(isPlaceSearchCandidate);
    expect(opened).toHaveLength(장소를_묻는_문장.length);
  });
});

describe("업체 추천으로 새지 않는다", () => {
  it.each(업체를_묻는_문장)("'%s'", (question) => {
    expect(isPlaceSearchCandidate(question)).toBe(false);
  });
});

describe("같은 낱말이 장소가 아닌 뜻으로 올 때는 열지 않는다", () => {
  it.each(장소를_묻는_게_아닌_문장)("'%s'", (question) => {
    expect(isPlaceSearchCandidate(question)).toBe(false);
  });

  it("함정 문장이 하나도 열리지 않는다", () => {
    // 넓혔을 때 이 숫자가 7 이었다. 0 이 아니면 어휘가 다시 헐거워진 것이다.
    expect(장소를_묻는_게_아닌_문장.filter(isPlaceSearchCandidate)).toEqual([]);
  });
});

describe("결혼 준비의 다른 질문은 건드리지 않는다", () => {
  it.each(관계없는_문장)("'%s'", (question) => {
    expect(isPlaceSearchCandidate(question)).toBe(false);
  });
});

describe("검색하지 말라는 말은 그대로 존중한다", () => {
  it.each([
    "상견례 장소는 찾지 마",
    "식당은 추천하지 마",
  ])("'%s'", (question) => {
    expect(isPlaceSearchCandidate(question)).toBe(false);
  });
});
