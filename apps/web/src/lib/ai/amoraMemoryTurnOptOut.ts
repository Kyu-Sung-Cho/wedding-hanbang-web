/**
 * 현재 사용자 발화의 명시적인 장기기억 금지만 판정한다.
 * 채팅 보관, 기존 기억 삭제, 계정 동의 설정을 바꾸거나 삭제 성공을 뜻하지 않는다.
 */
export function hasAmoraMemoryTurnOptOut(text: string): boolean {
  const request = text.normalize("NFKC")
    .replace(/```[\s\S]*?```|`[^`\n]*`/gu, " ")
    .replace(/"[^"\n]*"|'[^'\n]*'|“[^”]*”|‘[^’]*’|「[^」]*」|『[^』]*』/gu, " ")
    .replace(/^\s*>[^\n]*/gmu, " ");

  // 질문·걱정·일반 조언·금지 표현에 관한 설명을 명령으로 취급하지 않는다.
  const direct = /(?:기억(?:을|은)?\s*하|기억해\s*(?:두|놓)|(?:장기\s*)?(?:기억|메모리)(?:으로|에는|에|로|은|는|을|를)?\s*(?:저장하|남기|넣|담|추가하|보관하))지\s*(?:말고|말아(?:줘|주세요|요)?|마(?:세요|십시오|요|라)?|않았으면\s*(?:해요?|좋겠어요?))(?=$|[\s.!?。,;…])/gu;
  const wish = /기억(?:은|을)?\s*안\s*했으면\s*좋겠어요?(?=$|[\s.!?。,;…])/gu;
  const matches = [...request.matchAll(direct), ...request.matchAll(wish)];
  // '다음 상담에는 남기지 마'만으로 일반 일정·메모 저장을 금지했다고 추정하지 않는다.
  if (/이번\s*(?:대화|답변|상담)(?:에서|에)?만\s*(?:참고|사용|이용|쓰|써)/u.test(request)) {
    matches.push(...request.matchAll(/다음(?:번)?\s*(?:상담|대화)(?:에는|에)?\s*(?:남기|저장하)지\s*(?:말고|말아(?:줘|주세요|요)?|마(?:세요|요|라)?)(?=$|[\s.!?。,;…])/gu));
  }
  return matches.some((match) => {
    const tail = request.slice(match.index + match[0].length).split(/[.!?。;\n]/u, 1)[0];
    // 따옴표 없는 간접인용·가정형 질문도 실제 금지와 분리한다. 다른 문장의 직접 금지는 유지한다.
    return !/(?:라고|라며)\s*(?:(?:말|얘기|이야기|요청|부탁)(?:을|를)?\s*)?(?:했|하더|하던|하면|하는|해도)|라는\s*(?:말|문장|요청|뜻|예시)/u.test(tail);
  });
}
